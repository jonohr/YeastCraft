"""Collect installed, locked dependency notices without modifying upstream text.

Run after cargo fetch for both manifests and npm ci. The inventory intentionally
covers all locked Rust platforms and installed npm build tools, not only linked code.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'LICENSES/third-party'
TEXTS = OUT / 'texts'
TEXTS.mkdir(parents=True, exist_ok=True)
CARGO = shutil.which('cargo') or str(Path.home() / '.cargo/bin/cargo')
RUSTC = shutil.which('rustc') or str(Path.home() / '.cargo/bin/rustc')
records = []


def retain(path):
    content = path.read_bytes()
    name = hashlib.sha256(content).hexdigest() + '.txt'
    (TEXTS / name).write_bytes(content)
    return {'original': path.name, 'text': 'texts/' + name}


def notices(root):
    matches = []
    for path in sorted(root.rglob('*')):
        if not path.is_file() or 'node_modules' in path.relative_to(root).parts[:-1]:
            continue
        name = path.name.lower()
        if name.startswith(('license', 'licence', 'copying', 'notice', 'copyright', 'authors')):
            matches.append(retain(path))
    return matches


packages = {}
for manifest in ['rust/Cargo.toml', 'tools/ispindel-emulator/Cargo.toml']:
    data = json.loads(subprocess.check_output([CARGO, 'metadata', '--locked', '--offline',
        '--format-version', '1', '--manifest-path', str(ROOT / manifest)]))
    for package in data['packages']:
        if package['source']:
            packages[(package['name'], package['version'])] = package
for (name, version), package in sorted(packages.items()):
    root = Path(package['manifest_path']).parent
    texts = notices(root)
    if not texts:
        raise RuntimeError(f'Missing license notice: {name} {version}')
    records.append({'ecosystem': 'cargo', 'name': name, 'version': version,
        'license': package['license'], 'source': f'https://crates.io/api/v1/crates/{name}/{version}/download',
        'notices': texts})

lock = json.loads((ROOT / 'ui/package-lock.json').read_text())
for location, package in sorted(lock['packages'].items()):
    if not location:
        continue
    root = ROOT / 'ui' / location
    if not root.exists():  # Optional build binaries for other host platforms.
        continue
    texts = notices(root)
    # Architecture packages contain only the tool binary; its parent package
    # carries the matching upstream notice at the exact same version.
    for prefix, parent in [('node_modules/@esbuild/', 'esbuild'), ('node_modules/@rollup/rollup-', 'rollup')]:
        if not texts and location.startswith(prefix):
            upstream = ROOT / 'ui/node_modules' / parent
            assert json.loads((upstream / 'package.json').read_text())['version'] == package['version']
            texts = notices(upstream)
    if not texts:
        raise RuntimeError(f'Missing license notice: {location}')
    records.append({'ecosystem': 'npm', 'name': location.split('node_modules/')[-1],
        'version': package['version'], 'license': package.get('license'),
        'build_only': package.get('dev', False), 'source': package.get('resolved'),
        'integrity': package.get('integrity'), 'notices': texts})

sysroot = Path(subprocess.check_output([RUSTC, '--print', 'sysroot'], text=True).strip())
rustdoc = sysroot / 'share/doc/rust'
version = subprocess.check_output([RUSTC, '--version'], text=True).strip()
records.append({'ecosystem': 'rust-standard-library', 'name': 'Rust standard library',
    'version': version, 'source': 'https://static.rust-lang.org/dist/rustc-1.99.1-src.tar.xz',
    'notices': [retain(rustdoc / 'COPYRIGHT-library.html'),
        *[retain(p) for p in sorted((rustdoc / 'licenses').glob('*.txt'))]]})

# SQLite's bundled C implementation is public domain; retain its own dedication.
sqlite = next(Path(p['manifest_path']).parent / 'sqlite3/sqlite3.c'
    for p in packages.values() if p['name'] == 'libsqlite3-sys')
dedication = sqlite.read_text().split('*/', 1)[0] + '*/\n'
(OUT / 'SQLite-public-domain.txt').write_text(dedication)
(OUT / 'inventory.json').write_text(json.dumps(records, indent=2) + '\n')
lines = ['# Dependency notices', '',
    'Generated by `scripts/collect-licenses.py`. Upstream texts are retained verbatim.',
    'The inventory includes build/test and other-platform packages; listing does not imply runtime inclusion.',
    'See [the license review](../../docs/LICENSE_REVIEW.md) for source distribution and license choices.', '',
    '| Package | Version | Declared license | Notices |', '| --- | --- | --- | --- |']
for record in records:
    links = ', '.join(f"[{n['original']}]({n['text']})" for n in record['notices'])
    lines.append(f"| {record['name']} | {record['version']} | {record.get('license', 'See notices')} | {links} |")
(OUT / 'README.md').write_text('\n'.join(lines) + '\n')
print(f'Retained notices for {len(records)} package records; {len(list(TEXTS.iterdir()))} unique texts')
